#!/usr/bin/env node
// Static hosts and the API serve physical policy files. Keep their reviewed
// content in agreement with the JSON source used by the React policy pages.
const fs = require("node:fs");
const path = require("node:path");
const policies = require("../frontend/src/content/legalPolicies.json");
const root = path.resolve(__dirname, "..");
const formatDate = value =>
  new Intl.DateTimeFormat("en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${value}T00:00:00Z`));
const escape = value =>
  String(value).replace(
    /[&<>"']/g,
    char =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;",
      })[char]
  );

function validatePolicies() {
  for (const date of [policies.effectiveDate, policies.updatedDate]) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || Number.isNaN(Date.parse(date)))
      throw new Error("Legal policies need valid explicit revision dates.");
  }
  for (const key of ["terms", "privacy"]) {
    const document = policies[key];
    const ids = new Set();
    if (!document?.title || !document.sections?.length) throw new Error(`Missing policy: ${key}`);
    for (const section of document.sections) {
      if (!/^[a-z0-9-]+$/.test(section.id) || ids.has(section.id) || !section.title)
        throw new Error(`Invalid or duplicate legal section: ${key}/${section.id}`);
      ids.add(section.id);
      for (const link of section.links || []) {
        if (!link.label || !/^(https:\/\/|mailto:)/.test(link.href))
          throw new Error(`Invalid legal policy link: ${key}/${section.id}`);
      }
    }
  }
}

function renderLegalPage(key) {
  const document = policies[key];
  const sections = document.sections
    .map((section, index) => {
      const paragraphs = (section.paragraphs || [])
        .map(value => `<p>${escape(value)}</p>`)
        .join("\n");
      const items = section.items
        ? `<ul>${section.items.map(value => `<li>${escape(value)}</li>`).join("\n")}</ul>`
        : "";
      const links = section.links
        ? `<ul>${section.links.map(link => `<li><a href="${escape(link.href)}">${escape(link.label)}</a></li>`).join("\n")}</ul>`
        : "";
      return `<section aria-labelledby="${key}-${section.id}"><h2 id="${key}-${section.id}">${index + 1}. ${escape(section.title)}</h2>\n${paragraphs}\n${items}\n${links}</section>`;
    })
    .join("\n");
  return `<!doctype html>
<!-- Generated by scripts/build-legal-pages.js from frontend/src/content/legalPolicies.json. -->
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${escape(document.title)} - AutoPromote</title>
  <meta name="description" content="${escape(document.intro)}" />
  <link rel="canonical" href="https://autopromote.org/${key}/" />
  <style>
    * { box-sizing: border-box; }
    body { margin:0; background:#f7f7f2; color:#242034; font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Arial,sans-serif; line-height:1.7; }
    nav { display:flex; flex-wrap:wrap; gap:24px; align-items:center; max-width:960px; margin:auto; padding:24px; border-bottom:1px solid #dedfd9; }
    nav img { width:166px; height:auto; vertical-align:middle; }
    nav a { text-decoration:none; font-weight:600; }
    main { max-width:900px; margin:40px auto; padding:clamp(24px,5vw,56px); background:#fff; border:1px solid #e1e1d9; border-radius:14px; }
    h1 { font-size:clamp(30px,6vw,48px); letter-spacing:-.04em; line-height:1.15; }
    h2 { margin-top:30px; font-size:21px; }
    a { color:#613be4; overflow-wrap:anywhere; }
    li { margin-bottom:9px; }
    .revision { color:#625d70; font-size:.95em; }
    .skip { position:absolute; left:16px; top:-80px; padding:12px; background:#fff; }
    .skip:focus { top:8px; }
    :focus-visible { outline:3px solid #7758e9; outline-offset:4px; }
    @media(max-width:600px) { main { margin:20px 12px; } nav { gap:16px; } }
  </style>
</head>
<body>
  <a class="skip" href="#policy">Skip to policy</a>
  <nav aria-label="AutoPromote">
    <a href="https://autopromote.org/"><img src="https://autopromote.org/brand/autopromote-gradient.svg" alt="AutoPromote home" /></a>
    <a href="https://autopromote.org/#/docs">Product guides</a>
    <a href="https://autopromote.org/privacy/">Privacy</a>
    <a href="https://autopromote.org/terms/">Terms</a>
    <a href="mailto:${escape(policies.contactEmail)}">Contact</a>
  </nav>
  <main id="policy" tabindex="-1">
    <h1>${escape(document.title)}</h1>
    <p>${escape(document.intro)}</p>
    <article data-legal-content="${key}">
      <p class="revision">Effective date: <time datetime="${policies.effectiveDate}">${formatDate(policies.effectiveDate)}</time> · Last updated: <time datetime="${policies.updatedDate}">${formatDate(policies.updatedDate)}</time></p>
      ${sections}
    </article>
  </main>
</body>
</html>
`;
}

function syncLegalPages({ check = false } = {}) {
  validatePolicies();
  const stale = [];
  let count = 0;
  for (const key of ["terms", "privacy"]) {
    const html = renderLegalPage(key);
    const files = [
      `frontend/public/${key}/index.html`,
      `frontend/public/legal/${key}.html`,
      `public/legal/${key}.html`,
      `docs/${key}/index.html`,
      `frontend/docs/${key}/index.html`,
    ];
    for (const file of files) {
      const destination = path.join(root, file);
      if (check) {
        if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== html)
          stale.push(file);
      } else {
        fs.mkdirSync(path.dirname(destination), { recursive: true });
        fs.writeFileSync(destination, html);
      }
      count++;
    }
  }
  if (stale.length)
    throw new Error(
      `Legal policy pages need updating: ${stale.join(", ")}. Run node scripts/build-legal-pages.js.`
    );
  return count;
}

if (require.main === module) {
  try {
    const check = process.argv.includes("--check");
    console.log(
      `${check ? "Verified" : "Updated"} ${syncLegalPages({ check })} legal policy pages.`
    );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { renderLegalPage, syncLegalPages, validatePolicies };
