const test=require('node:test'),assert=require('node:assert/strict');
const {Readable}=require('node:stream');
const {hash}=require('../../src/modelRuntime/contract');
const {importGeneratedSource}=require('../../src/modelRuntime/importGenerated');
const bytes=Buffer.from('CPU contract fixture; not a generated video');
function fixture({corrupt=false,collision=false}={}) {
  const output={video:{name:'generated_shot.mp4',sha256:hash(bytes),bytes:bytes.length,mediaType:'video/mp4'},
    width:1280,height:704,fpsNumerator:24,fpsDenominator:1,frameCount:121,durationTicks:453750,
    origin:'generated_illustration',reviewRequired:true,confidence:null};
  const core={schemaVersion:1,status:'completed',ownerUid:'owner',projectId:'project',capability:'generate_video',output,
    files:[{...output.video,storagePath:'private/result.mp4',generation:'1'}],provenance:{executionKind:'test_double'}};
  const artifact={...core,artifactHash:hash(core)};let writes=0;const bindings=[];let metadata;
  const dest={name:'destination',exists:async()=>[!!metadata],getMetadata:async()=>[metadata],
    save:async(data,options)=>{writes++;assert.equal(options.preconditionOpts.ifGenerationMatch,0);assert.deepEqual(data,bytes);
      metadata={...options.metadata,generation:'2',size:data.length};}};
  if(collision)metadata={metadata:{ownerUid:'other'},size:bytes.length};
  const source={getMetadata:async()=>[{metadata:{ownerUid:'owner'},size:bytes.length}],
    createReadStream:()=>Readable.from([corrupt?Buffer.alloc(bytes.length):bytes])};
  const bucket={file:(name,options)=>{if(name==='private/result.mp4'){assert.equal(options.generation,'1');return source;}return dest;}};
  return {args:{ownerUid:'owner',projectId:'project',artifact,bucket,
    bindSource:async b=>bindings.push(b),urlFor:async()=>'/cpu-contract-fixture.mp4'},bindings,writes:()=>writes};
}
test('generated import uses an immutable owned source and original source-binding contract',async()=>{
  const f=fixture(),a=await importGeneratedSource(f.args),b=await importGeneratedSource(f.args);
  assert.equal(f.writes(),1);assert.equal(a.contentHash,hash(bytes));assert.equal(a.id,b.id);
  assert.equal(f.bindings[0].sourceAssetId,a.id);assert.equal(f.bindings[0].projectId,'project');
  assert.match(a.storagePath,/^studio\/sources\/owner\/model-[a-f0-9]{64}\.mp4$/);
});
test('changed generated bytes fail before a source is written or bound',async()=>{
  const f=fixture({corrupt:true});await assert.rejects(importGeneratedSource(f.args),/CHANGED/);
  assert.equal(f.writes(),0);assert.equal(f.bindings.length,0);
});
test('import cannot use another owner or overwrite a colliding source',async()=>{
  const f=fixture();await assert.rejects(importGeneratedSource({...f.args,ownerUid:'other'}),/SCOPE/);
  const c=fixture({collision:true});await assert.rejects(importGeneratedSource(c.args),/COLLISION/);assert.equal(c.writes(),0);
});
