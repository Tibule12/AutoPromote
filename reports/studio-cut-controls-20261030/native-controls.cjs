// Headless, muted, actual App controls against fresh local emulators only.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '../..');
const directory = process.argv[2];
const config = JSON.parse(fs.readFileSync(path.join(directory, 'browser-private.json')));
const runtime = JSON.parse(fs.readFileSync(path.join(directory, 'config.json')));
assert.equal(runtime.env.GCLOUD_PROJECT, 'demo-autopromote-credits');
assert.equal(new URL(config.origin).hostname, '127.0.0.1');
const proof = path.join(directory, 'cut-controls-proof');
fs.mkdirSync(proof, { recursive: true, mode: 0o700 });
const { clickStudioControl } = require(path.join(root, 'test/e2e/playwright/studio-timeline-layout'));
const { seek } = require(path.join(root, 'test/e2e/playwright/studio-stability/flows'));
const title = 'Cut and Chipmunk regression — isolated local test';
const results = {};
async function backup(page, name) {
  await page.getByTestId('studio-pro-timeline').waitFor({ timeout: 90000 });
  const show = page.getByRole('button', { name: 'Show media', exact: true });
  if (await show.isVisible()) await show.click();
  const head = page.locator('.studio-project-rail__head');
  if (!await head.evaluate(element => element.open)) await head.locator(':scope > summary').click();
  await page.getByTestId('studio-save-project').click();
  const versions = page.getByLabel('Include saved versions in backup', { exact: true });
  if (await versions.isChecked()) await versions.uncheck();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download project backup', exact: true }).click();
  const destination = path.join(proof, name + '.autopromote.json');
  await (await download).saveAs(destination);
  return JSON.parse(fs.readFileSync(destination)).snapshot;
}
const durations = snapshot => snapshot.timeline.map(clip => [clip.startRequest, clip.endRequest]);
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--mute-audio'] });
  const context = await browser.newContext({ viewport: { width: 1600, height: 1000 },
    recordVideo: { dir: path.join(proof, 'recordings') } });
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    return url.hostname === '127.0.0.1' || ['data:', 'blob:'].includes(url.protocol) ? route.continue() : route.abort();
  });
  const page = await context.newPage(); page.setDefaultTimeout(25000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  try {
    await page.goto(config.origin);
    await page.getByRole('button', { name: 'Sign In', exact: true }).click();
    await page.locator('#login-email').fill(config.email);
    await page.locator('#login-password').fill(config.password);
    await page.locator('form input[type=checkbox]').check();
    await page.locator('form button[type=submit]').click();
    await page.getByTestId('shared-credit-balance').waitFor();
    await page.getByRole('button', { name: 'Viral Clip Studio', exact: true }).first().click();
    await page.locator('.creator-studio-dropzone input[type=file]').setInputFiles(path.join(directory, 'source.mp4'));
    await page.getByRole('button', { name: 'Open Creator Studio', exact: true }).click();
    await page.getByTestId('studio-pro-timeline').waitFor({ timeout: 90000 });
    const showMedia = page.getByRole('button', { name: 'Show media', exact: true });
    if (await showMedia.isVisible()) await showMedia.click();
    const projectHead = page.locator('.studio-project-rail__head');
    if (!await projectHead.evaluate(element => element.open)) await projectHead.locator(':scope > summary').click();
    await page.getByLabel('Project name', { exact: true }).fill(title);
    await seek(page, 1);
    await page.getByRole('button', { name: 'Razor tool', exact: true }).click();
    const clip = page.getByTestId('pro-video-clip-1');
    const box = await clip.boundingBox();
    await clip.click({ position: { x: box.width / 2, y: box.height / 2 } });
    await page.getByTestId('pro-video-clip-2').waitFor();
    const split = durations(await backup(page, 'razor-split'));
    assert.equal(split.length, 2); assert(Math.abs(split[0][1] - 4) < .12);
    assert.equal(split[0][1], split[1][0]);
    results.razorAtClickedFrame = split;
    await page.getByTestId('studio-undo-button').click();
    await page.getByTestId('pro-video-clip-2').waitFor({ state: 'detached' });
    await page.getByTestId('studio-redo-button').click();
    await page.getByTestId('pro-video-clip-2').waitFor();
    await page.getByTestId('studio-undo-button').click();
    await page.getByRole('button', { name: 'Select tool', exact: true }).click();
    results.razorUndoRedo = true;
    await seek(page, 2);
    await page.getByTestId('pro-quick-trim-start').click();
    const startTrim = durations(await backup(page, 'trim-start'));
    assert.deepEqual(startTrim, [[2, 8]]); results.trimStart = startTrim;
    await seek(page, 3);
    await page.getByTestId('pro-quick-trim-end').click();
    assert.deepEqual(durations(await backup(page, 'trim-end')), [[2, 5]]);
    results.trimEnd = true;
    await page.getByTestId('studio-undo-button').click();
    await clickStudioControl(page, page.getByRole('button', { name: 'Cut', exact: true }));
    await page.getByLabel('Remove from time', { exact: true }).fill('1');
    await page.getByLabel('Remove to time', { exact: true }).fill('2');
    const track = page.getByTestId('pro-track-row-video');
    await track.getByRole('button', { name: 'Lock track', exact: true }).click();
    assert(await page.getByTestId('remove-marked-range').isDisabled());
    await track.getByRole('button', { name: 'Unlock track', exact: true }).click();
    await page.getByTestId('remove-marked-range').click();
    assert.deepEqual(durations(await backup(page, 'marked-removal')), [[2, 3], [4, 8]]);
    results.markedRemovalAndLock = true;
    await clickStudioControl(page, page.getByRole('button', { name: 'Sound', exact: true }));
    await page.getByTestId('audio-remix-preset-chipmunk').click();
    const chipmunk = await backup(page, 'chipmunk');
    assert.equal(chipmunk.audioRemix.preset, 'chipmunk');
    assert.equal(chipmunk.audioRemix.pitch, 12); assert.equal(chipmunk.previewSpeed, 1);
    results.chipmunkSaved = true;
    await page.reload(); await page.getByTestId('shared-credit-balance').waitFor();
    await page.getByRole('button', { name: 'Viral Clip Studio', exact: true }).first().click();
    await page.getByRole('button', { name: title, exact: true }).click();
    const reopened = await backup(page, 'reopened');
    assert.deepEqual(durations(reopened), durations(chipmunk));
    assert.deepEqual(reopened.audioRemix, chipmunk.audioRemix);
    results.coldReopen = true; results.browserErrors = errors;
    assert.deepEqual(errors, []);
    await page.screenshot({ path: path.join(proof, 'final.png') });
    console.log(JSON.stringify(results));
  } catch (error) {
    results.failure = error.message;
    await page.screenshot({ path: path.join(proof, 'failure.png') }).catch(() => {});
    throw error;
  } finally {
    fs.writeFileSync(path.join(proof, 'results.json'), JSON.stringify(results, null, 2));
    await context.close(); await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
